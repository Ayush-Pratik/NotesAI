"""
export_service.py
=================
Generates downloadable TXT and PDF reports for summaries and question sets.

Uses ReportLab for PDF generation. Produces human-readable, well-structured
documents suitable for student study materials.
"""

from __future__ import annotations

import io
from datetime import datetime
from typing import Any, Dict, List, Optional

from validators import (
    AnyQuestion,
    LongAnswerQuestion,
    MCQQuestion,
    ShortAnswerQuestion,
    TrueFalseQuestion,
)


# ---------------------------------------------------------------------------
# TXT Export
# ---------------------------------------------------------------------------

def _separator(char: str = "─", width: int = 70) -> str:
    return char * width


def _section_header(title: str) -> str:
    sep = _separator("═")
    return f"\n{sep}\n  {title.upper()}\n{sep}\n"


def export_summary_txt(summary: dict, doc_title: str = "Study Notes") -> bytes:
    """
    Generate a plain-text summary report.

    Parameters
    ----------
    summary : dict
        Output from summarizer.generate_summary().
    doc_title : str
        Document title.

    Returns
    -------
    bytes
        UTF-8 encoded TXT content.
    """
    lines = []
    ts = datetime.now().strftime("%Y-%m-%d %H:%M")

    lines.append("=" * 70)
    lines.append(f"  NotesAI — Summary Report")
    lines.append(f"  Document : {doc_title}")
    lines.append(f"  Generated: {ts}")
    lines.append("=" * 70)

    lines.append(_section_header("Summary"))
    lines.append(summary.get("summary_text", ""))

    key_concepts = summary.get("key_concepts", [])
    if key_concepts:
        lines.append(_section_header("Key Concepts"))
        for concept in key_concepts:
            lines.append(f"  • {concept}")

    defs = summary.get("important_definitions", [])
    if defs:
        lines.append(_section_header("Important Definitions"))
        for d in defs:
            lines.append(f"  • {d}")

    lines.append(f"\n{_separator()}")
    lines.append(
        "  Note: This summary was generated by AI from the supplied notes.\n"
        "  Always verify important information against your original source."
    )
    lines.append(_separator())

    return "\n".join(lines).encode("utf-8")


def export_questions_txt(
    questions: List[AnyQuestion],
    doc_title: str = "Study Notes",
    include_answers: bool = True,
) -> bytes:
    """
    Generate a plain-text question and answer report.

    Parameters
    ----------
    questions : list
        List of validated question objects.
    doc_title : str
        Document title.
    include_answers : bool
        If False, answers and explanations are omitted (practice sheet).

    Returns
    -------
    bytes
        UTF-8 encoded TXT content.
    """
    lines = []
    ts = datetime.now().strftime("%Y-%m-%d %H:%M")

    lines.append("=" * 70)
    lines.append(f"  NotesAI — Questions {'& Answers ' if include_answers else ''}Report")
    lines.append(f"  Document : {doc_title}")
    lines.append(f"  Generated: {ts}")
    if not include_answers:
        lines.append("  Mode     : Practice Sheet (answers hidden)")
    lines.append("=" * 70)

    for idx, q in enumerate(questions, start=1):
        lines.append(f"\n{'─' * 70}")
        lines.append(f"  Question {idx}")
        lines.append(f"  Difficulty: {q.difficulty.value.upper()}")
        topic = getattr(q, "topic", None)
        if topic:
            lines.append(f"  Topic: {topic}")
        lines.append("─" * 70)

        if isinstance(q, MCQQuestion):
            lines.append(f"\n{q.question}\n")
            for key, val in q.options.items():
                lines.append(f"  {key}. {val}")
            if include_answers:
                lines.append(f"\n  ✓ Correct Answer: {q.correct_answer}")
                lines.append(f"\n  Explanation:\n  {q.explanation}")
                lines.append(f"\n  Source Evidence:\n  \"{q.source_evidence}\"")

        elif isinstance(q, ShortAnswerQuestion):
            lines.append(f"\n{q.question}\n")
            if include_answers:
                lines.append(f"  Expected Answer:\n  {q.expected_answer}")
                if q.key_points:
                    lines.append(f"\n  Key Points:")
                    for kp in q.key_points:
                        lines.append(f"    • {kp}")
                lines.append(f"\n  Explanation:\n  {q.explanation}")
                lines.append(f"\n  Source Evidence:\n  \"{q.source_evidence}\"")
            else:
                lines.append("  _" * 25)

        elif isinstance(q, LongAnswerQuestion):
            lines.append(f"\n{q.question}\n")
            if include_answers:
                lines.append(f"  Model Answer:\n  {q.model_answer}")
                lines.append(f"\n  Main Points:")
                for mp in q.main_points:
                    lines.append(f"    • {mp}")
                if q.marking_guidance:
                    lines.append(
                        f"\n  Marking Guidance (AI-generated, not official):\n"
                        f"  {q.marking_guidance}"
                    )
                lines.append(f"\n  Source Evidence:\n  \"{q.source_evidence}\"")
            else:
                lines.append("\n  " + ("_" * 60 + "\n") * 5)

        elif isinstance(q, TrueFalseQuestion):
            lines.append(f"\n  Statement: {q.statement}\n")
            if include_answers:
                answer_str = "TRUE" if q.correct_answer else "FALSE"
                lines.append(f"  ✓ Answer: {answer_str}")
                lines.append(f"\n  Explanation:\n  {q.explanation}")
                lines.append(f"\n  Source Evidence:\n  \"{q.source_evidence}\"")
            else:
                lines.append("  Answer: TRUE / FALSE")

    lines.append(f"\n{'=' * 70}")
    lines.append(
        "  Note: Questions generated by AI from the supplied notes.\n"
        "  Always verify answers against your original source material."
    )
    lines.append("=" * 70)

    return "\n".join(lines).encode("utf-8")


